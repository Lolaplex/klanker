#!/usr/bin/env bash
# board.sh — the klanker challenges slot board.
# Validates challenges/*/entry.md frontmatter + evidence rules, prints the
# slot table. Regenerates the marked block in challenges/CATALOG.md.
#
#   board.sh            validate + print table
#   board.sh --write    regenerate the <!-- board:begin --> block in CATALOG.md
#   board.sh --check    fail if CATALOG.md's board block is stale
#
# Fails loud when:
#   - an entry claims landed with no evidence/ artifacts (self-report is not evidence)
#   - an entry is claimed while a `needs:` dep is not landed|waived
#   - entry.md frontmatter is missing required fields
set -uo pipefail
cd "$(dirname "$0")/.."

MODE="${1:-print}"
FAIL=0

fm() { # fm <file> <key> -> frontmatter value (first match)
  awk -v k="$2" 'index($0, k ":") == 1 { sub("^[^:]*:[[:space:]]*", ""); print; exit }' "$1"
}
status_of() { fm "challenges/$1/entry.md" status; }
needs_of()  { fm "challenges/$1/entry.md" needs | tr -d '[]' | tr ',' '\n' | sed 's/^ *//; s/ *$//' | grep -v '^$'; }

declare -A STATUS AREA SURFACE EVIDENCE NEEDS

for d in challenges/*/; do
  n=$(basename "$d"); [ "$n" = "_template" ] && continue
  [ -f "$d/entry.md" ] || { echo "board: $n missing entry.md"; FAIL=1; continue; }
  e="$d/entry.md"
  for f in name area needs accept surface status evidence provenance; do
    grep -q "^$f:" "$e" || { echo "board: $n entry.md missing field: $f"; FAIL=1; }
  done
  s=$(status_of "$n"); STATUS[$n]="$s"
  AREA[$n]=$(fm "$e" area); SURFACE[$n]=$(fm "$e" surface)
  EVIDENCE[$n]=$(fm "$e" evidence); NEEDS[$n]=$(needs_of "$n" | tr '\n' ' ')
  case "$s" in
    landed)
      if [ -z "$(find "$d/evidence" -type f 2>/dev/null | head -1)" ]; then
        echo "board: $n status=landed but evidence/ is empty — landed claims need artifacts"; FAIL=1
      fi ;;
    claimed)
      for dep in ${NEEDS[$n]}; do
        ds=$(status_of "$dep")
        case "$ds" in
          landed|waived) ;;
          *) echo "board: $n claimed but needs $dep (${ds:-missing})"; FAIL=1 ;;
        esac
      done ;;
    open|waived) ;;
    *) echo "board: $n bad status '$s' (open|claimed|landed|waived)"; FAIL=1 ;;
  esac
done

# --- generate board block ---
gen_block() {
  echo '<!-- board:begin — generated by scripts/board.sh --write; do not edit -->'
  printf '| slot | area | needs | surface | status | evidence |\n'
  printf '|---|---|---|---|---|---|\n'
  for n in $(printf '%s\n' "${!STATUS[@]}" | sort); do
    nd="—"; [ -n "${NEEDS[$n]}" ] && nd=$(echo "${NEEDS[$n]}" | tr ' ' '\n' | grep -v '^$' | sort | tr '\n' ',' | sed 's/,$//; s/,/, /g')
    printf '| %s | %s | %s | %s | %s | %s |\n' "$n" "${AREA[$n]}" "$nd" "${SURFACE[$n]}" "${STATUS[$n]}" "${EVIDENCE[$n]}"
  done
  echo ""
  echo '## Unblocked now (all needs landed/waived)'
  echo ""
  local names="" any=0
  for n in $(printf '%s\n' "${!STATUS[@]}" | sort); do
    [ "${STATUS[$n]}" = "open" ] || continue
    local ok=1
    for dep in ${NEEDS[$n]}; do
      case "$(status_of "$dep")" in landed|waived) ;; *) ok=0 ;; esac
    done
    if [ "$ok" = 1 ]; then names="$names$n "; any=1; fi
  done
  if [ $any = 1 ]; then
    echo -n '```'
    for n in $names; do printf '%s, ' "$n"; done | sed 's/, $//'
    echo ''
    echo '```'
  else
    echo "_(none)_"
  fi
  echo ""
  echo '<!-- board:end -->'
}

if [ "$MODE" = "--write" ] || [ "$MODE" = "--check" ]; then
  GEN=$(gen_block)
  if [ "$MODE" = "--write" ]; then
    awk -v gen="$GEN" '
      /<!-- board:begin/ { print gen; skip=1; next }
      /<!-- board:end/   { skip=0; next }
      !skip { print }
    ' challenges/CATALOG.md > challenges/CATALOG.md.tmp && mv challenges/CATALOG.md.tmp challenges/CATALOG.md
    echo "board: CATALOG.md regenerated"
  else
    CURRENT=$(awk '/<!-- board:begin/,/<!-- board:end/' challenges/CATALOG.md)
    if [ "$CURRENT" = "$GEN" ]; then
      echo "board: CATALOG.md fresh"
    else
      echo "board: CATALOG.md STALE — run scripts/board.sh --write" >&2; FAIL=1
    fi
  fi
fi

if [ "$MODE" != "--write" ] && [ "$MODE" != "--check" ]; then
  printf '%-24s %-8s %-10s %-6s %s\n' SLOT AREA SURFACE STATUS EVIDENCE
  for n in $(printf '%s\n' "${!STATUS[@]}" | sort); do
    printf '%-24s %-8s %-10s %-6s %s\n' "$n" "${AREA[$n]}" "${SURFACE[$n]}" "${STATUS[$n]}" "${EVIDENCE[$n]}"
  done
fi

[ "$FAIL" = 0 ] && echo "board: clean" || { echo "board: FAILURES above" >&2; exit 1; }
